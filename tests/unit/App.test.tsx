import { render, screen, within } from "@testing-library/react";
import { describe, expect, it } from "vitest";
import { App } from "../../src/App.tsx";

describe("App", () => {
  it("renders the JD2CV shell without the template placeholder", () => {
    render(<App />);
    expect(screen.getByRole("heading", { level: 1 }).textContent).not.toBe("resume-sg");
    expect(document.body.textContent).not.toContain("This product was generated by the factory");
    expect(within(screen.getByRole("navigation")).getByRole("link", { name: "JD2CV" })).toBeTruthy();
  });
});
